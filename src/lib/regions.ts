/**
 * Normalizes city/district search matching
 */
export function matchRegionOrCity(
  targetCity: string | null | undefined,
  targetDistrict: string | null | undefined,
  targetAddress: string | null | undefined,
  selectedCity: string
): boolean {
  if (!selectedCity || selectedCity === "Barcha shaharlar") return true;

  const search = selectedCity.toLowerCase().trim();
  const c = (targetCity || "").toLowerCase().trim();
  const d = (targetDistrict || "").toLowerCase().trim();
  const a = (targetAddress || "").toLowerCase().trim();

  // If selectedCity is e.g. "Toshkent shahri" or "Toshkent", check matches:
  if (c.includes(search) || search.includes(c)) return true;
  if (d.includes(search) || search.includes(d)) return true;
  if (a.includes(search) || search.includes(a)) return true;

  // Handle generic shorthand e.g. "Toshkent" matching "Toshkent shahri" or "Toshkent viloyati"
  const cleanSearch = search.replace("shahri", "").replace("viloyati", "").replace("respublikasi", "").trim();
  if (cleanSearch && (c.includes(cleanSearch) || d.includes(cleanSearch) || a.includes(cleanSearch))) {
    return true;
  }

  return false;
}
